func library(names ...string) []migrations.Migration {
	var out []migrations.Migration
	for i, n := range names {
		out = append(out, migrations.Migration{ID: i + 1, Name: n,
			Up:   fmt.Sprintf("CREATE TABLE auth_%s (p uuid REFERENCES {{principals}} (id));\n", n),
			Down: fmt.Sprintf("DROP TABLE auth_%s;\n", n)})
	}
	return out
}

