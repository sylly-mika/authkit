func TestWriteNewNeverOverwrites(t *testing.T) {
	path := filepath.Join(t.TempDir(), "000009_authkit_core.up.sql")
	if err := os.WriteFile(path, []byte("applied"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := writeNew(path, "replacement"); err == nil {
		t.Fatal("writeNew replaced an existing file")
	}
	if b, _ := os.ReadFile(path); string(b) != "applied" {
		t.Fatalf("the existing file now reads %q", b)
	}
}

