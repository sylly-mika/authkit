func TestRunRefusesABadPrincipalsName(t *testing.T) {
	for _, bad := range []string{"users; DROP TABLE x", "Users", "user", "order", "group", "left", "auth_sessions", "pg_users"} {
		dir, lock := appDir(t)
		if _, err := run(options{principals: bad, out: dir, lock: lock, version: "v0.1.0"}); err == nil || !strings.HasPrefix(err.Error(), "authkit-gen: ") {
			t.Errorf("%q was rendered (%v), want an authkit-gen: refusal", bad, err)
		}
		if entries, _ := os.ReadDir(dir); len(entries) != 0 {
			t.Errorf("%q left %v in the migrations directory", bad, entries)
		}
		if _, err := os.Stat(lock); !os.IsNotExist(err) {
			t.Errorf("%q wrote the lock (%v)", bad, err)
		}
	}
}

