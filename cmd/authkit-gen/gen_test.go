func library(names ...string) []migrations.Migration {
	var out []migrations.Migration
	for i, n := range names {
		out = append(out, migrations.Migration{ID: i + 1, Name: n,
			Up:   fmt.Sprintf("CREATE TABLE auth_%s (p uuid REFERENCES {{principals}} (id));\n", n),
			Down: fmt.Sprintf("DROP TABLE auth_%s;\n", n)})
	}
	return out
}

func TestRunWritesOnlyWhatANewerLibraryAdded(t *testing.T) {
	dir, lock := appDir(t, "000008_rls_policies.up.sql")
	if _, err := run(options{principals: "users", out: dir, lock: lock, version: "v0.1.0", library: library("core")}); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "000010_app.up.sql"), []byte("SELECT 1;\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	written, err := run(options{principals: "users", out: dir, lock: lock, version: "v0.2.0", library: library("core", "passkeys")})
	if want := []string{"000011_authkit_passkeys.up.sql", "000011_authkit_passkeys.down.sql"}; err != nil || !slices.Equal(names(written), want) {
		t.Fatalf("the upgrade wrote %v (%v), want %v", names(written), err, want)
	}
	if up, _ := os.ReadFile(written[0]); !strings.HasPrefix(string(up), "-- Generated by authkit-gen from github.com/sylly-mika/authkit v0.2.0, migration 0002_passkeys.") {
		t.Fatalf("up = %s", up)
	}
	var l lockFile
	b, _ := os.ReadFile(lock)
	if err := json.Unmarshal(b, &l); err != nil || len(l.Migrations) != 2 || l.Migrations[0].File != "000009_authkit_core" || l.Migrations[1].File != "000011_authkit_passkeys" {
		t.Fatalf("lock = %+v (%v)", l, err)
	}
}

func TestRunRefusesALockedMigrationThatChanged(t *testing.T) {
	dir, lock := appDir(t, "000008_rls_policies.up.sql")
	lib := library("core")
	if _, err := run(options{principals: "users", out: dir, lock: lock, version: "v0.1.0", library: lib}); err != nil {
		t.Fatal(err)
	}
	lib[0].Up += "CREATE INDEX idx_auth_core_p ON auth_core (p);\n"
	written, err := run(options{principals: "users", out: dir, lock: lock, version: "v0.1.1", library: lib})
	if err == nil || len(written) != 0 || !strings.Contains(err.Error(), "000009_authkit_core") {
		t.Fatalf("a changed 0001 wrote %v (%v), want a refusal naming 000009_authkit_core", names(written), err)
	}
}

func TestRunRefusesASecondCopyWithoutTheLock(t *testing.T) {
	dir, lock := appDir(t, "000008_rls_policies.up.sql", "000009_authkit_core.up.sql", "000009_authkit_core.down.sql")
	written, err := run(options{principals: "users", out: dir, lock: lock, version: "v0.1.0"})
	if err == nil || len(written) != 0 {
		t.Fatalf("000009_authkit_core present and no lock: wrote %v (%v), want a refusal", names(written), err)
	}
	if _, err := os.Stat(lock); !os.IsNotExist(err) {
		t.Fatalf("the refusal wrote the lock (%v)", err)
	}
}

func TestRunWritesNothingWhenTheLockCannotBeWritten(t *testing.T) {
	dir, _ := appDir(t, "000008_rls_policies.up.sql")
	lock := filepath.Join(t.TempDir(), "missing", "authkit.lock")
	if written, err := run(options{principals: "users", out: dir, lock: lock, version: "v0.1.0"}); err == nil || len(written) != 0 {
		t.Fatalf("wrote %v (%v), want a refusal before any write", names(written), err)
	}
	if entries, _ := os.ReadDir(dir); len(entries) != 1 {
		t.Fatalf("the migrations directory holds %v, want only the app's migration", entries)
	}
}
